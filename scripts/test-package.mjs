import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import assert from 'node:assert/strict';
import {installPackage} from './package/install.mjs';
import {verifyConsumer} from './package/consumer.mjs';
import {compareInstalledFiles} from './package/manifest.mjs';

const exec=promisify(execFile),root=resolve('.'),npm=process.env.npm_execpath;
if(!npm) throw new Error('Use npm run test:package');
const packageVersion=JSON.parse(await readFile('package.json','utf8')).version;
const stage=process.env.AQA_PACKAGE_STAGE||'final';assert(/^(final|candidate-[0-9]+)$/.test(stage));
const artifacts=resolve('artifacts/package',packageVersion,...(stage==='final'?[]:[stage]));await mkdir(artifacts,{recursive:true});
const run=(file,args,cwd=root)=>exec(process.execPath,[file,...args],{cwd,windowsHide:true,maxBuffer:8*1024*1024,timeout:180000});
const {packed,archive,sha256,consumer}=await installPackage({run,npm,artifacts});
const {binVersion,binHelp,result,design,authoring,agent,service}=await verifyConsumer({run,npm,root,consumer,packageVersion});
const installedFiles=await compareInstalledFiles(packed,root,consumer);
const bundle=JSON.parse(await readFile('contracts/release.json','utf8'));
const xml=JSON.parse(await readFile('contracts/xml-release.json','utf8'));
const report={status:'passed',stage,engineVersion:packed.version,contractVersion:bundle.contractVersion,archive,sha256,integrity:packed.integrity,shasum:packed.shasum,bundle,xml,agentProtocol:JSON.parse(await readFile('contracts/agent-protocol/pin.json','utf8')),consumer,installedFiles,binSmoke:{version:binVersion,help:binHelp},typecheck:{valid:'passed',invalid:'rejected',compiler:'6.0.3'},runtime:JSON.parse(result.stdout.trim()),design:JSON.parse(design.stdout.trim()),authoring:JSON.parse(authoring.stdout.trim()),agent:JSON.parse(agent.stdout.trim()),service:JSON.parse(service.stdout.trim())};
await writeFile(join(artifacts,'verification.json'),JSON.stringify(report,null,2)+'\n');
await writeFile(join(artifacts,'pack-manifest.json'),JSON.stringify(packed,null,2)+'\n');
console.log(JSON.stringify(report));
